#!/usr/bin/env python3
"""Which families can load a GGUF -- derived from the recipes, written into oflm-add.

The capability is the MANIFEST's: a recipe that emits a "gguf" section gives
the engine the f32-scale twin it swaps in when the model ships a model.gguf
(open_kernels/recipes/manifest.py). So the list of families that can is not a
judgement call in oflm-add -- it is DERIVED, by building each shipped spec's
manifest and looking for the section.

    python utilities/generate-gguf-families.py            # write the list
    python utilities/generate-gguf-families.py --check     # fail if it is stale

CI runs the --check, the way it checks the settings registry: a family that
gains a recipe (and with it a GGUF section) belongs in the list, and the list
is what oflm-add uses to decide whether a GGUF repo can be installed at all.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "open_kernels"))
os.environ.setdefault("OPEN_KERNELS_UNVALIDATED", "1")   # the geometry is not the question here

try:
    from recipes.manifest import manifest  # noqa: E402
    from recipes.load import load_spec  # noqa: E402
except ImportError as exc:          # the recipes need numpy; say so, do not traceback
    raise SystemExit(f"generate-gguf-families: the recipes need numpy ({exc}); "
                     "run this with a python that has it (the ironvenv, or a venv with numpy)")

SPECS = REPO / "open_kernels" / "recipes" / "specs"
OF_ADD = REPO / "utilities" / "oflm-add" / "oflm_add" / "__init__.py"
BEGIN = "# --- GGUF-capable families (generated by utilities/generate-gguf-families.py) ---"
END = "# --- end of the generated list ---"


def capable_families() -> dict[str, str]:
    """family -> a note on why, for the families whose manifest carries the section."""
    out: dict[str, str] = {}
    for spec_path in sorted(SPECS.glob("*.json")):
        try:
            spec = load_spec(spec_path)
            m = manifest(spec)
        except Exception as exc:                       # a spec the recipe refuses
            print(f"[WARN] {spec_path.name}: {exc}", file=sys.stderr)
            continue
        if "gguf" in m:
            # The section is not enough: the f32-scale KERNEL SET has to be built
            # too, or the engine would swap in a manifest whose kernels are not
            # there. The f32 builds carry the scales flag in their env.
            # The twins are listed in the Q4_1 manifest's builds (the f32 manifest is
            # the one that uses them); the env carries the flag that says which pool
            # layout the build compiles for.
            twins = [b for b in m.get("builds", {}).values()
                     if any("SCALES_F32" in k for k in b.get("env", {}))]
            if twins:
                out.setdefault(spec.family, f"the {spec.family} recipe emits the f32-scale twin")
            else:
                print(f"[WARN] {spec.family}: the manifest has a gguf section but no f32-scale "
                      "kernel set is built -- not GGUF-capable", file=sys.stderr)
    return out


def render(fams: dict[str, str]) -> str:
    lines = [BEGIN, "GGUF_CAPABLE_FAMILIES = {"]
    for fam in sorted(fams):
        lines.append(f'    "{fam}",')
    lines.append("}")
    lines.append(END)
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the list in oflm-add is stale")
    a = ap.parse_args()

    fams = capable_families()
    block = render(fams)
    text = OF_ADD.read_text()
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", text, re.S)
    if not m:
        print(f"generate-gguf-families: {OF_ADD} has no generated block", file=sys.stderr)
        return 1
    if m.group(0) == block:
        print(f"gguf-capable families: {', '.join(sorted(fams))} (up to date)")
        return 0
    if a.check:
        print("generate-gguf-families: the list in oflm-add is STALE -- run\n"
              "    python utilities/generate-gguf-families.py", file=sys.stderr)
        print(f"the recipes say: {', '.join(sorted(fams))}", file=sys.stderr)
        return 1
    OF_ADD.write_text(text[: m.start()] + block + text[m.end():])
    print(f"wrote {len(fams)} families into {OF_ADD.relative_to(REPO)}: {', '.join(sorted(fams))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
