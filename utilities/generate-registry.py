#!/usr/bin/env python3
"""Generate settings_registry_generated.hpp from settings.json + code scan.

Usage:
    generate-registry.py --settings src/config/settings.json
                         --scan-output /tmp/scan.json
                         --output src/config/settings_registry_generated.hpp
     
    If --scan-output is not provided, runs scan-settings.py automatically.
"""
import argparse, json, subprocess, sys
from pathlib import Path

# Required manual fields (fail if missing)
REQUIRED_MANUAL = ["type", "scope", "delivery", "category"]

# Scan discoveries that are intentionally NOT user settings. The reverse
# cross-check fails the build for any flag/env var the scanner finds that is
# neither in settings.json nor listed here: a new engine knob must be
# classified (add it to settings.json) or explicitly excluded (add it here,
# with a reason). Without this, an unregistered option left both generated
# files unchanged and the CI diff check passed -- no drift protection at all.
NON_SETTING_FLAGS = {
    # command selection / CLI plumbing, not tunable values
    "--accept-shipped", "--asr", "--asrmodel", "--bench-iterations",
    "--command", "--cors", "--embed", "--embeddingmodel", "--filter",
    "--force", "--host", "--image", "--imagegen", "--imagemodel",
    "--json", "--keep-all", "--max-batch", "--out", "--port",
    "--prompt", "--prompt-name", "--q-len", "--quiet", "--seed",
    "--size", "--socket", "--preemption", "--img-pre-resize",
}
NON_SETTING_ENV_VARS = {
    # install layout / paths
    "OFLM_CONFIG_PATH", "OFLM_SETTINGS_PATH", "OFLM_MODELINFO_PATH",
    "OFLM_MODEL_PATH", "OFLM_MODEL_DIR", "OFLM_EXECUTABLE", "OFLM_PYTHON",
    "OFLM_PACK_SCRIPT", "OFLM_ADD_SCRIPT",
    # runtime plumbing
    "OFLM_BACKEND", "OFLM_PLATFORM", "OFLM_SERVE_PORT",
    "OFLM_DISABLE_UPDATE_CHECK", "OFLM_HF_OWNER",
    # device / kernel selection
    "OFLM_NPU_DEVICE_ID", "OFLM_NPU_DISABLE", "OFLM_XCLBIN_PATH",
    "OFLM_KERNELS_DIR", "OFLM_OPEN_KERNELS_DIR", "OFLM_DIFFUSION_KERNELS_DIR",
    "OFLM_WHISPER_KERNELS_DIR",
    # debug / engineering knobs (not for the settings UI)
    "OFLM_DECODE_AUTO_THRESHOLD", "OFLM_DET_ROUTE", "OFLM_GRANITE_ENGINE",
    "OFLM_OPEN_ATTN_BLOCK", "OFLM_OPEN_DISPATCH_LOG", "OFLM_OPEN_DXB_LOG",
    "OFLM_OPEN_GEMM_BLOCK", "OFLM_OPEN_GEMM_BLOCK_MIN",
    "OFLM_OPEN_HOST_ATTN", "OFLM_OPEN_HOST_ATTN_DECODE",
    "OFLM_OPEN_LAYER_MAJOR", "OFLM_OPEN_MOE_BATCH",
    "OFLM_OPEN_MOE_BATCH_LOG", "OFLM_OPEN_MOE_REDISPATCH",
    "OFLM_OPEN_OMP_PASSIVE", "OFLM_OPEN_OMP_THREADS",
    "OFLM_OPEN_QUIET", "OFLM_OPEN_READ_FENCE",
    "OFLM_GGUF_POOL_Q41",                # the f32-numerics bisect: a GGUF model on the q4_1 twin
    "OFLM_OPEN_ROUTE_SENTINEL", "OFLM_OPEN_SPIN_US",
    "OFLM_OPEN_STAGE_MAJOR", "OFLM_OPEN_STEP_TRACE",
    "OFLM_OPEN_SUBMIT_AHEAD", "OFLM_OPEN_TIMEOUT_MS",
    "OFLM_OPEN_TIMEOUT_RETRY_MS", "OFLM_ROUTE_CHECK",
    "OFLM_WHISPER_DUMP_MEL", "OFLM_WHISPER_ENGINE",
    "OFLM_WHISPER_PROTOCOL",
    # The Uno draft pass (K2-Horizon): a presence switch, read as "== 1", that
    # turns on a pass the MODEL has to ship (its lora_file). It is a feature
    # flag for a draft path still under development, not a preference about how
    # to run a model, so it stays out of the settings UI. It becomes a
    # per-model setting when the drafter settles.
    "OFLM_SPECULATIVE",
}

def generate_cpp_header(settings):
    """Generate C++ header content from settings list."""
    lines = []
    lines.append("/// \\file settings_registry_generated.hpp")
    lines.append("/// \\brief AUTO-GENERATED settings registry — do not edit manually.")
    lines.append("/// \\note Generated by utilities/generate-registry.py from settings.json + code scan.")
    lines.append("/// \\note To add a setting: add CLI flag/env var to code, run generate-settings target,")
    lines.append("///       fill in manual fields in settings.json, regenerate.")
    lines.append("#pragma once")
    lines.append("")
    lines.append('#include "settings_registry.hpp"')
    lines.append("")
    lines.append("namespace oflm::config {")
    lines.append("")
    lines.append("inline const std::vector<SettingDef>& build_registry() {")
    lines.append("    static const std::vector<SettingDef> registry = {")

    for s in settings:
        lines.append("        SettingDef{")
        lines.append(f'            .key = "{s["key"]}",')
        lines.append(f'            .cli_flag = "{s.get("cli_flag", "")}",')
        lines.append(f'            .env_var = "{s.get("env_var", "")}",')
        # Escape description
        desc = s.get("description", "").replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'            .description = "{desc}",')
        # Type
        type_map = {"enum": "SettingType::ENUM", "int": "SettingType::INT",
                    "bool": "SettingType::BOOL", "string": "SettingType::STRING"}
        lines.append(f'            .type = {type_map.get(s["type"], "SettingType::STRING")},')
        # Options
        if s.get("options"):
            lines.append("            .options = {")
            for opt in s["options"]:
                opt_desc = opt.get("description", "").replace('\\', '\\\\').replace('"', '\\"')
                lines.append(f'                {{"{opt["value"]}", "{opt_desc}"}},')
            lines.append("            },")
        else:
            lines.append("            .options = {},")
        # Min/max
        if s.get("min_value") is not None:
            lines.append(f'            .min_value = {s["min_value"]},')
        else:
            lines.append("            .min_value = std::nullopt,")
        if s.get("max_value") is not None:
            lines.append(f'            .max_value = {s["max_value"]},')
        else:
            lines.append("            .max_value = std::nullopt,")
        # Presets
        if s.get("presets"):
            presets = ", ".join(str(p) for p in s["presets"])
            lines.append(f"            .presets = {{{presets}}},")
        else:
            lines.append("            .presets = {},")
        # Default. A JSON bool would land as Python's "True"/"False" in the
        # C++ string, so spell the booleans the way the engine reads them.
        default = s.get("default_value", "")
        if isinstance(default, bool):
            default = "true" if default else "false"
        else:
            default = str(default)
        lines.append(f'            .default_value = "{default}",')
        # Scope
        scope_map = {"global": "SettingScope::GLOBAL", "per_model": "SettingScope::PER_MODEL",
                     "both": "SettingScope::BOTH"}
        lines.append(f'            .scope = {scope_map.get(s["scope"], "SettingScope::GLOBAL")},')
        # Reload required
        lines.append(f'            .reload_required = {"true" if s.get("reload_required") else "false"},')
        # Category
        lines.append(f'            .category = "{s.get("category", "general")}",')
        # Registry key
        lines.append(f'            .registry_key = "{s.get("registry_key", "")}",')
        # Delivery
        delivery_map = {"direct": "DeliveryMechanism::DIRECT", "env_var": "DeliveryMechanism::ENV_VAR",
                        "api_field": "DeliveryMechanism::API_FIELD", "registry": "DeliveryMechanism::REGISTRY"}
        lines.append(f'            .delivery = {delivery_map.get(s["delivery"], "DeliveryMechanism::DIRECT")},')
        lines.append("        },")

    lines.append("    };")
    lines.append("    return registry;")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace oflm::config")
    lines.append("")
    
    return "\n".join(lines)

def validate_settings(settings):
    """Check that all settings have required manual fields."""
    errors = []
    for s in settings:
        key = s.get("key", "?")
        for field in REQUIRED_MANUAL:
            if field not in s:
                errors.append(f"Setting '{key}' missing required manual field: {field}")
        if s.get("type") == "enum" and not s.get("options"):
            errors.append(f"Setting '{key}' is enum but has no options")
        if s.get("type") == "int" and s.get("min_value") is None:
            errors.append(f"Setting '{key}' is int but has no min_value")
    return errors

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--settings", default="src/config/settings.json")
    parser.add_argument("--scan-output", default=None, help="Pre-existing scan output (runs scanner if not provided)")
    parser.add_argument("--output", default="src/config/settings_registry_generated.hpp")
    parser.add_argument("--source-dir", default="src")
    args = parser.parse_args()

    # Load settings.json
    with open(args.settings) as f:
        data = json.load(f)
    settings = data.get("settings", [])

    # Validate
    errors = validate_settings(settings)
    if errors:
        print("ERROR: settings.json validation failed:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        sys.exit(1)

    # Run scanner if no pre-existing output
    if args.scan_output:
        with open(args.scan_output) as f:
            scan = json.load(f)
    else:
        result = subprocess.run(
            [sys.executable, "utilities/scan-settings.py", "--source-dir", args.source_dir],
            capture_output=True, text=True
        )
        if result.returncode != 0:
            print(f"ERROR: scanner failed: {result.stderr}", file=sys.stderr)
            sys.exit(1)
        scan = json.loads(result.stdout)

    # Cross-check, both directions:
    # 1. settings.json entries must exist in code (drift the other way)
    scan_flags = set(scan.get("cli_flags", {}).keys())
    scan_envs = set(scan.get("env_vars", {}).keys())
    for s in settings:
        if s.get("cli_flag") and s["cli_flag"] not in scan_flags:
            print(f"WARNING: {s['cli_flag']} in settings.json but not found in vm_args.hpp")
        if s.get("env_var") and s["env_var"] not in scan_envs:
            print(f"WARNING: {s['env_var']} in settings.json but not found in source code")
    # 2. scan discoveries must be classified: in settings.json, or in the
    #    explicit exclusion lists above. An unclassified discovery fails the
    #    build -- otherwise adding an engine option changes neither generated
    #    file and the CI diff check passes, defeating the drift protection.
    settings_flags = {s["cli_flag"] for s in settings if s.get("cli_flag")}
    settings_envs = {s["env_var"] for s in settings if s.get("env_var")}
    unclassified_flags = sorted(scan_flags - settings_flags - NON_SETTING_FLAGS)
    unclassified_envs = sorted(scan_envs - settings_envs - NON_SETTING_ENV_VARS)
    if unclassified_flags or unclassified_envs:
        print("ERROR: the code scan found CLI flags/env vars that settings.json does not",
              file=sys.stderr)
        print("classify and the generator does not exclude:", file=sys.stderr)
        for f in unclassified_flags:
            print(f"  - CLI flag {f}: add it to src/config/settings.json (with type/",
                  file=sys.stderr)
            print(f"      scope/delivery/category) or to NON_SETTING_FLAGS in",
                  file=sys.stderr)
            print(f"      utilities/generate-registry.py with a reason.", file=sys.stderr)
        for v in unclassified_envs:
            print(f"  - env var {v}: add it to src/config/settings.json (with type/",
                  file=sys.stderr)
            print(f"      scope/delivery/category) or to NON_SETTING_ENV_VARS in",
                  file=sys.stderr)
            print(f"      utilities/generate-registry.py with a reason.", file=sys.stderr)
        print("Unclassified options must be classified for the registry to stay",
              file=sys.stderr)
        print("in sync with the code.", file=sys.stderr)
        sys.exit(1)

    # Generate C++ header
    cpp = generate_cpp_header(settings)
    with open(args.output, "w") as f:
        f.write(cpp)
    print(f"Generated {args.output} ({len(settings)} settings)")

if __name__ == "__main__":
    main()
