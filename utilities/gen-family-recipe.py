#!/usr/bin/env python3
"""Generate a recipe MODULE from a spec derivation (the next mechanical step).

    python utilities/gen-family-recipe.py --spec qwen36moe-flint --family flint \
        --design designs/flint --from qwen36moe --dry-run

`derive-recipe` writes the facts; this command turns them into a real
`open_kernels/recipes/<family>.py` that:

  * fills in the derived constants (topk / slots / attn cores / quant law);
  * delegates geometry, layout, pack_plan, programs, builds and manifest to
    the CLOSEST recipe whose `_check()` accepts the spec;
  * raises a named OpRangeError for the fields that genuinely differ, so the
    wall is explicit and located instead of a generic refusal.

It NEVER claims the design works. It writes the module into
`open_kernels/recipes/<family>.py` (or --out) and prints the exact remaining
steps: supply the design/kernel sources, register the family, run
build-new-spec and the numeric gates. `--dry-run` writes nothing.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
RECIPES = ROOT / "open_kernels" / "recipes"
FAMILIES_PY = RECIPES / "families.py"


def register_dispatch(family: str, dry: bool) -> bool:
    """Add the family to families.family_module() + FAMILIES (idempotent).

    Returns True if the file changed. This is pure registration: the recipe
    module itself still names its own walls and needs a real design.
    """
    text = FAMILIES_PY.read_text(encoding="utf-8")
    dispatch = (f'    if name == "{family}":\n'
                f'        from . import {family}\n'
                f'        return {family}\n')
    changed = False
    if f'name == "{family}"' not in text:
        marker = '    if name == "qwen36moe":\n'
        if marker not in text:
            raise SystemExit("gen-family-recipe: unexpected families.py dispatch shape")
        text = text.replace(marker, dispatch + marker, 1)
        changed = True
    # Add to the FAMILIES tuple (not NOT_IMPLEMENTED: a generated recipe exists).
    m = re.search(r"^FAMILIES = \(([^)]*)\)$", text, re.M)
    if m and f'"{family}"' not in m.group(1):
        new_tuple = "FAMILIES = (" + m.group(1).rstrip() + f', "{family}")'
        text = text[:m.start()] + new_tuple + text[m.end():]
        changed = True
    if changed and not dry:
        FAMILIES_PY.write_text(text, encoding="utf-8")
    return changed


def derive(spec_path: Path, work: Path) -> dict[str, Any]:
    """Run derive-recipe in-process and read its data (no subprocess needed)."""
    sys.path.insert(0, str(ROOT / "utilities"))
    import importlib.util
    sp = importlib.util.spec_from_file_location("_derive_recipe", ROOT / "utilities" / "derive-recipe.py")
    dr = importlib.util.module_from_spec(sp)
    sp.loader.exec_module(dr)
    sys.path.insert(0, str(ROOT / "open_kernels"))
    from recipes.load import load_spec                    # noqa: PLC0415
    s = load_spec(spec_path).to_dict()
    return {
        "spec": s,
        "hardware": dr.hardware_invariants(),
        "quant": dr.quant_law(str(s.get("quant") or "")),
        "template": dr.template_for(s),
        "capabilities": dr.capability_constants(s),
        "inputs": dr.design_inputs(s, dr.template_for(s)),
    }


def render(family: str, base: str, design: str, d: dict[str, Any]) -> str:
    """A thin module: derived constants + delegation + explicit difference wall."""
    if base == family:
        raise SystemExit(f"gen-family-recipe: --base {base!r} equals --family {family!r}; "
                         "a generated recipe cannot delegate to itself")
    s = d["spec"]
    cap = d["capabilities"]
    quant = d["quant"]
    diffs = []
    if cap.get("SHARED_SLOTS", 0) and int(s.get("shared_expert_intermediate") or 0) != int(s.get("moe_intermediate") or 0):
        diffs.append((
            "shared_expert_intermediate",
            s.get("shared_expert_intermediate"),
            s.get("moe_intermediate"),
            f"the closest recipe requires a shared expert of one routed width; "
            f"this model has {s.get('shared_expert_intermediate')} = "
            f"{cap.get('SHARED_SLOTS')} routed widths. The shared expert must be "
            f"split into that many expert slots by the design."))
    diff_lines = "\n".join(
        f'        "{key}": {{"actual": {actual!r}, "closest_recipe_expects": {expected!r}, '
        f'"reason": {reason!r}}},' for key, actual, expected, reason in diffs)

    return f'''"""Generated recipe for {family} (from a spec derivation).

Mechanically generated by `oflm dev gen-family-recipe`. It fills in the
spec-derived constants and delegates the arithmetic to the closest recipe,
`{base}`, EXCEPT for the differences below, which are named walls.

The design and kernel sources are NOT generated: supply `{design}` with the
family's gen_kernels.py and *.cc/*.h, then run build-new-spec and the numeric
gates. A successful export is not a support claim.
"""
from __future__ import annotations

from . import {base} as _base
from .catalogue import OpRangeError
from .spec import ModelSpec

FAMILY = "{family}"
BASE = "{base}"
DESIGN = "{design}"

# --- spec-derived constants (from the GGUF header + universal NPU facts) ---
CH = {quant.get("CH", 5120)}
PER_CALL = {quant.get("PER_CALL", 2)}
N_CORES = {d["hardware"]["N_CORES"]}
TOPK = {cap.get("TOPK_MAX", 0)}
SLOTS = {cap.get("SLOTS", 0)}
EXPERTS = {cap.get("EXPERTS", 0)}
SHARED_SLOTS = {cap.get("SHARED_SLOTS", 0)}
ATTN_CORES = {cap.get("ATTN_CORES", 4)}

# The differences from the closest recipe that this spec actually names.
DIFFERENCES = {{{diff_lines}}}


def _check(spec: ModelSpec) -> None:
    if spec.family != FAMILY:
        raise OpRangeError(f"{{FAMILY}} recipe given a {{spec.family!r}} spec")
    if DIFFERENCES:
        what = "; ".join(
            f"{{k}}={{v['actual']!r}} (closest expects {{v['closest_recipe_expects']!r}}): "
            f"{{v['reason']}}" for k, v in DIFFERENCES.items())
        raise OpRangeError(f"{{FAMILY}}: {{what}}")


def recipe(spec: ModelSpec, max_ctx: int = 4096):
    _check(spec)
    return _base.recipe(spec, max_ctx)


def __getattr__(name: str):
    """Delegate the rest of the recipe surface; _check runs inside recipe()."""
    if name in ("geometry", "layout", "pool", "pool_bytes", "pack_plan",
                "programs", "builds", "manifest_layout", "hf_config_check",
                "attn_flags", "probe_env", "gguf_quant"):
        return getattr(_base, name)
    if name in ("KERNEL_SOURCES", "KERNEL_SOURCES_MOE", "GEN_KERNELS", "BLOCK_SOURCES"):
        return getattr(_base, name, None)
    raise AttributeError(f"module {{__name__!r}} has no attribute {{name!r}}")
'''


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spec", required=True, help="the derived spec (name or path)")
    ap.add_argument("--family", required=True, help="the new family name")
    ap.add_argument("--base", default="", help="closest recipe to delegate to (default: from derivation)")
    ap.add_argument("--design", default="", help="design dir for the new layer kind")
    ap.add_argument("--out", default="", help="output path (default: recipes/<family>.py)")
    ap.add_argument("--force", action="store_true",
                    help="overwrite an existing recipe file (never do this to an implemented family)")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    sp = Path(a.spec)
    if not sp.is_file():
        stem = a.spec.removesuffix(".json")
        for base in (RECIPES / "specs", RECIPES / "candidates"):
            cand = base / (stem + ".json")
            if cand.is_file():
                sp = cand
                break
    if not sp.is_file():
        raise SystemExit(f"gen-family-recipe: no such spec: {a.spec}")
    d = derive(sp, ROOT / "build" / "derive-recipe" / sp.stem)
    base = a.base or d["template"]["closest"].split("/")[0].replace("-", "_")
    # A generated module must never delegate to ITSELF: that creates an
    # import cycle and silently replaces a working recipe with a stub.
    if base == a.family:
        raise SystemExit(
            f"gen-family-recipe: --base {base!r} equals --family {a.family!r}. "
            "A new family must delegate to an EXISTING recipe (e.g. qwen36moe), "
            "not to itself. Choose a distinct --family name such as 'flint'.")
    # Never overwrite an implemented recipe without an explicit, named opt-in.
    out = Path(a.out) if a.out else RECIPES / f"{a.family}.py"
    if out.is_file() and not a.dry_run and not a.force:
        raise SystemExit(
            f"gen-family-recipe: {out} already exists. Refusing to overwrite an "
            "existing recipe with a generated stub. Choose a new --family name, "
            "or pass --force only if you intend to replace it.")
    design = a.design or d["inputs"]["design"].split("...")[0].strip()
    text = render(a.family, base, design, d)
    if a.dry_run:
        would_wire = register_dispatch(a.family, dry=True)
        print(f"gen-family-recipe: would write {out}")
        print(f"  base recipe: {base}; design: {design}")
        print(f"  families.py: {'would register ' + a.family if would_wire else 'already registered'}")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"gen-family-recipe: wrote {out}")
    wired = register_dispatch(a.family, dry=False)
    print(f"  base recipe: {base}; design: {design}")
    print(f"  families.py: {'registered ' + a.family if wired else 'already registered'}")
    print("next: supply the design + kernel sources at " + design + ", then:")
    print("      oflm dev build-new-spec --spec <name> && numeric gates")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
