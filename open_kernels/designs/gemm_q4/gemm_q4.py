r"""Batched q4_1 GEMM on the NPU: Y[M, K] rows against W[N, K] pool chunks.

Same dataflow as designs/gemv_q4, with an M dimension: each core still streams
its slice of the weight bands once, but now keeps M activation tables and emits
M band accumulators per band. The weight DMA per band is unchanged, so time vs
M measures how much compute headroom sits under the weight stream - which is
what decides whether NPU prefill can beat the iGPU.

GEMM_BLOCKED=1 switches to the blocked dataflow: the weights arrive k-tile-major
and every band's accumulator stays resident, so the per-token table is one
256-wide slice (576 B) instead of the whole K (4608 B) and M reaches 24 instead
of 8. Weight bytes per pass are the same either way; what changes is how many
tokens ride along. Needs GEMM_PER_CALL=1 and make_test.py --blocked.

Shape via env GEMM_N / GEMM_K / GEMM_RS / GEMM_CORES / GEMM_M.

Build (WSL):  GEMM_M=4 python build_design.py designs/gemm_q4/gemm_q4.py designs/gemm_q4/build_m4
Run:          (cd designs/gemm_q4 && run_kernel run_m4.cfg)   (see make_test.py)
"""

